"""Build the Render deploy bundle and push it to a PRIVATE GitHub repo (it contains the official documents).

    cd backend && uv run python ../deploy/deploy_render.py SaiPranav13188

Render then builds it from deploy/render/render.yaml (New → Blueprint → pick the repo).
"""
from __future__ import annotations

import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STAGE = ROOT / "deploy" / ".build" / "render"


def run(*cmd: str, cwd: Path = STAGE) -> str:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=True).stdout


def light_vectors() -> Path:
    """Cached hashing-embedder vectors for the default corpus (built on first local light-engine start)."""
    import os

    os.environ.setdefault("HAATHI_EMBEDDER", "hash")
    sys.path.insert(0, str(ROOT / "backend"))
    from app.config import get_settings
    from app.corpus import Corpus
    from app.retrieval.pipeline import Retriever

    chunks = Corpus().chunks
    digest = hashlib.sha1("\x1e".join(c.index_text for c in chunks).encode()).hexdigest()[:12]
    path = ROOT / "data" / "index" / f"emb_hash_{digest}.npz"
    if not path.exists():
        Retriever(chunks, get_settings(), embedder="hash", reranker="lexical", vector_store="numpy")
    return path


def stage() -> None:
    git_dir = STAGE / ".git"
    keep = git_dir.exists()
    if keep:
        shutil.move(str(git_dir), str(STAGE.parent / ".render-git"))
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    if keep:
        shutil.move(str(STAGE.parent / ".render-git"), str(git_dir))
    for f in ("Dockerfile", "render.yaml"):
        shutil.copy(ROOT / "deploy" / "render" / f, STAGE / f)
    base = run("uv", "export", "--no-dev", "--no-hashes", "--no-emit-project", "--frozen", cwd=ROOT / "backend")
    (STAGE / "requirements.txt").write_text("\n".join(l for l in base.splitlines() if l and not l.startswith(("#", " ", "-e"))) + "\n")
    ignore = shutil.ignore_patterns("__pycache__", ".venv", ".pytest_cache", ".hypothesis", ".coverage", "tests", ".env",
                                    "*.log", "locustfile.py")
    shutil.copytree(ROOT / "backend", STAGE / "backend", ignore=ignore)
    data = STAGE / "data"
    for sub in ("schemes", "seed"):
        shutil.copytree(ROOT / "data" / sub, data / sub)
    shutil.copy(ROOT / "data" / "manifest.csv", data / "manifest.csv")
    (data / "raw").mkdir(parents=True)
    for p in (ROOT / "data" / "raw").iterdir():
        if p.suffix.lower() in {".pdf", ".html", ".json"}:
            shutil.copy(p, data / "raw" / p.name)
    (data / "index").mkdir()
    shutil.copytree(ROOT / "data" / "index" / "parsed", data / "index" / "parsed")
    shutil.copy(light_vectors(), data / "index")
    (data / "cache").mkdir()
    ctx = ROOT / "data" / "cache" / "context_notes.json"
    if ctx.exists():
        shutil.copy(ctx, data / "cache" / ctx.name)
    (STAGE / "README.md").write_text("# haathi-deploy (private)\n\nRender deploy bundle for "
                                     "[Haathi](https://github.com/SaiPranav13188/haathi). Generated by `deploy/deploy_render.py`; "
                                     "includes official documents, so keep this repository private.\n")
    size = sum(f.stat().st_size for f in STAGE.rglob("*") if f.is_file() and ".git" not in f.parts) / 1e6
    print(f"staged {STAGE} ({size:.0f} MB)")


def push(user: str) -> None:
    repo = f"{user}/haathi-deploy"
    if not (STAGE / ".git").exists():
        run("git", "init", "-q", "-b", "main")
    run("git", "add", "-A")
    if run("git", "status", "--porcelain").strip():
        run("git", "commit", "-q", "-m", "Deploy bundle")
    exists = subprocess.run(["gh", "repo", "view", repo], capture_output=True).returncode == 0
    if not exists:
        run("gh", "repo", "create", repo, "--private", "--source", ".", "--remote", "origin", "--push",
            "--description", "Private Render deploy bundle for Haathi (contains official documents)")
    else:
        if "origin" not in run("git", "remote"):
            run("git", "remote", "add", "origin", f"https://github.com/{repo}.git")
        run("git", "push", "-q", "-u", "origin", "main")
    print(f"pushed https://github.com/{repo} (private)")


if __name__ == "__main__":
    stage()
    push(sys.argv[1])
